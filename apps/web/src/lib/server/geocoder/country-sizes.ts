import { feature } from "topojson-client";
import type { Feature, MultiPolygon, Polygon, Position } from "geojson";
import type { NaturalEarthTopology } from "./index.js";

/** Mean Earth radius (IUGG), in km. */
const EARTH_RADIUS_KM = 6371.0088;

const rad = (deg: number) => (deg * Math.PI) / 180;

/** A ring's area on the sphere in km² (unsigned), by the Chamberlain–Duquette formula. */
function ringAreaKm2(ring: Position[]): number {
  const n = ring.length;
  if (n < 3) return 0;
  let total = 0;
  for (let i = 0; i < n; i++) {
    const lower = ring[i]!;
    const middle = ring[(i + 1) % n]!;
    const upper = ring[(i + 2) % n]!;
    total += (rad(upper[0]!) - rad(lower[0]!)) * Math.sin(rad(middle[1]!));
  }
  return Math.abs((total * EARTH_RADIUS_KM * EARTH_RADIUS_KM) / 2);
}

/** A (multi)polygon's area in km²: outer rings minus their holes. */
export function areaKm2(geometry: Polygon | MultiPolygon): number {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  let area = 0;
  for (const [outer, ...holes] of polygons) {
    if (!outer) continue;
    area += ringAreaKm2(outer) - holes.reduce((sum, hole) => sum + ringAreaKm2(hole), 0);
  }
  return area;
}

function areasBy(
  features: Feature<Polygon | MultiPolygon | null, { c: string | null }>[],
  keep: (code: string) => boolean,
): Map<string, number> {
  const areas = new Map<string, number>();
  for (const f of features) {
    const code = f.properties.c;
    if (!code || !f.geometry || !keep(code)) continue;
    areas.set(code, (areas.get(code) ?? 0) + areaKm2(f.geometry));
  }
  return areas;
}

const toSizes = (areas: Map<string, number>): Record<string, number> =>
  Object.fromEntries(
    [...areas]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([code, area]) => [code, Math.max(1, Math.round(Math.sqrt(area)))]),
  );

export interface CountrySizes {
  /** √area in km per country code, as the geocoder codes countries. */
  countries: Record<string, number>;
  /** √area in km per overseas Region code. */
  overseasRegions: Record<string, number>;
}

/** Country and overseas-Region sizes (√area in km) from the geocoder's boundary data. */
export function countrySizesFromTopology(
  topology: NaturalEarthTopology,
  overseasRegionCodes: readonly string[],
): CountrySizes {
  const countries = feature(topology, topology.objects.countries).features as Feature<
    Polygon | MultiPolygon | null,
    { c: string }
  >[];
  const regions = feature(topology, topology.objects.regions).features as Feature<
    Polygon | MultiPolygon | null,
    { c: string | null }
  >[];
  const wanted = new Set(overseasRegionCodes);
  return {
    countries: toSizes(areasBy(countries, () => true)),
    overseasRegions: toSizes(areasBy(regions, (code) => wanted.has(code))),
  };
}

/** The shared `country-sizes.ts` module for the given sizes. */
export function generateCountrySizesModule(sizes: CountrySizes): string {
  const record = (r: Record<string, number>) =>
    Object.entries(r)
      .map(([code, km]) => `  ${JSON.stringify(code)}: ${km},`)
      .join("\n");
  return `// Generated by apps/web/src/lib/server/geocoder/build-country-sizes.ts from the geocoder's Natural Earth data. Do not edit.

/** A country's size: the square root of its area, in km, per ISO 3166-1 alpha-2 code. */
export const COUNTRY_SIZE_KM: Readonly<Record<string, number>> = {
${record(sizes.countries)}
};

/** Each overseas Region's own size (√area in km), per Region code; see OVERSEAS_REGIONS. */
export const OVERSEAS_REGION_SIZE_KM: Readonly<Record<string, number>> = {
${record(sizes.overseasRegions)}
};

/**
 * The size (√area in km) of a country, or of an overseas Region given its Region
 * code (it counts as its own country), or null when unknown.
 */
export function countrySizeKm(code: string | null | undefined): number | null {
  if (!code) return null;
  return COUNTRY_SIZE_KM[code] ?? OVERSEAS_REGION_SIZE_KM[code] ?? null;
}

/** \`countrySizeKm\` in metres, shaped as a \`CountrySizeLookup\` for \`roundHedge\`. */
export function countrySizeMeters(code: string): number | null {
  const km = countrySizeKm(code);
  return km === null ? null : km * 1000;
}
`;
}
